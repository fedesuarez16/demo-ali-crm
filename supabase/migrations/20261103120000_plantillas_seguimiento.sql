-- Plantillas genéricas de seguimiento (fuera del ciclo de 8 toques).
-- `codigo` es el valor que se guarda en cola_seguimientos.seguimientos_count para pedir esta plantilla
-- (ej. 300 = baja_valor). El workflow n8n "seguimiento v2" toma las filas cuyo contador sea un código
-- activo con nombre_ycloud cargado, manda esa plantilla por YCloud y devuelve al lead al T3 (+30 días).
-- `nombre_ycloud` queda vacío hasta que Meta/YCloud aprueba la plantilla: sin él, no se envía.

CREATE TABLE IF NOT EXISTS public.plantillas_seguimiento (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo        integer NOT NULL UNIQUE CHECK (codigo > 10 AND codigo <> 100),
  nombre        text    NOT NULL,
  mensaje       text    NOT NULL,
  nombre_ycloud text    UNIQUE CHECK (nombre_ycloud IS NULL OR nombre_ycloud ~ '^[a-z0-9_]+$'),
  activa        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN public.plantillas_seguimiento.codigo IS 'Valor de seguimientos_count que dispara esta plantilla (fuera de 0..10 y distinto de 100).';
COMMENT ON COLUMN public.plantillas_seguimiento.nombre_ycloud IS 'Nombre de la plantilla aprobada en YCloud. NULL = pendiente de aprobación, no se envía.';

ALTER TABLE public.plantillas_seguimiento ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "plantillas_seguimiento_all" ON public.plantillas_seguimiento;
CREATE POLICY "plantillas_seguimiento_all" ON public.plantillas_seguimiento FOR ALL USING (true) WITH CHECK (true);

